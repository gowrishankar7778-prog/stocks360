  function getAmcList() {
    const map = {};
    allFunds.forEach((f) => {
      if (!map[f.fundHouse]) {
        map[f.fundHouse] = {
          fundHouse: f.fundHouse,
          amcShort: f.amcShort || f.fundHouse.replace(" Mutual Fund", ""),
          schemes: [],
          totalAumCr: 0
        };
      }
      map[f.fundHouse].schemes.push(f);
      map[f.fundHouse].totalAumCr += (f.aumCr || 0);
    });
    return Object.values(map);
  }

