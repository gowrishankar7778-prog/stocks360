  // Build Autocomplete Suggestions for AMC or Mutual Fund Search
  function buildSuggestions(query) {
    const q = (query || "").trim().toLowerCase();
    const amcs = getAmcList();
    const results = [];

    if (!q) {
      // Default top suggestions when user focuses search box
      amcs.slice(0, 4).forEach((a) => {
        results.push({
          type: "AMC",
          title: a.fundHouse,
          subtitle: `View all ${a.schemes.length} Mutual Funds maintained by ${a.amcShort} (AUM: ₹${a.totalAumCr.toLocaleString("en-IN")} Cr)`,
          value: a.fundHouse
        });
      });
      allFunds.slice(0, 6).forEach((f) => {
        results.push({
          type: "SCHEME",
          title: f.name,
          subtitle: `${f.category} • NAV: ₹${Number(f.nav).toFixed(2)} • 3Y CAGR: +${f.return3Y}%`,
          value: f.schemeCode
        });
      });
      return results;
    }

    // 1. Match AMCs first
    amcs.forEach((a) => {
      if (
        a.fundHouse.toLowerCase().includes(q) ||
        a.amcShort.toLowerCase().includes(q)
      ) {
        results.push({
          type: "AMC",
          title: `${a.fundHouse} (All ${a.schemes.length} Schemes)`,
          subtitle: `AMC Portfolio • Click or press Enter to view all mutual funds maintained by ${a.amcShort}`,
          value: a.fundHouse
        });
      }
    });

    // 2. Match individual Mutual Fund Schemes
    allFunds.forEach((f) => {
      if (
        f.name.toLowerCase().includes(q) ||
        f.shortName.toLowerCase().includes(q) ||
        f.fundHouse.toLowerCase().includes(q) ||
        f.category.toLowerCase().includes(q)
      ) {
        results.push({
          type: "SCHEME",
          title: f.name,
          subtitle: `${f.fundHouse} • ${f.category} • NAV: ₹${Number(f.nav).toFixed(2)} • 3Y CAGR: +${f.return3Y}%`,
          value: f.schemeCode
        });
      }
    });

    return results.slice(0, 12);
  }

